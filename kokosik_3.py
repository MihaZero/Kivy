d = [12, 4, 9, 1, 6, 3]
def merge_sort(spisok): # Каждый раз, когда я буду его вызывать и давать какой-то spisok, он будет разрезать его пополам, пока не останутся одиночные числа, а потом собирать обратно по порядку».
    if len(spisok) <= 1:# Если в списке остался 1 элемент,то останавливаем деление
        return spisok
    mid = len(spisok) // 2 # делим общее количество элементов на 2
    left = merge_sort(spisok[:mid])#дробим левую часть,пока не отсаниться 1 элемент
    right = merge_sort(spisok[mid:])#дробим правую часть,пока не отсаниться 1 элемент
    sorted_list = []
    i = j = 0# Создаем два указателя (i для левого списка, j для правого) равные 0
    while i < len(left) and j < len(right):#запускаем цикл,который будет сравнивать элементы слева и справа
        if left[i] <= right[j]:
            sorted_list.append(left[i]) # Забираем левое число и добавляем его в наш итоговый список
            i=i+1 #Сдвигаем левый указатель на один шаг вперед (вправо)
        else:
            sorted_list.append(right[j])# Забираем левое число и добавляем его в наш итоговый список
            j=j+1#Сдвигаем правый указатель на один шаг вперед (вправо)
    while i < len(left):# Если левый список уже закончился, просто переносим все остатки из левого
        sorted_list.append(left[i])
        i=i+1
    while j < len(right):# Если правый список уже закончился, просто переносим все остатки из левого
        sorted_list.append(right[j])
        j=j+1
    return sorted_list #Возвращаем полностью собранный и отсортированный список 
print("исходный список:",d)
print("Полученный список:", merge_sort(d))

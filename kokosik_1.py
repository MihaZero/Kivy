spisok = [2, 5, 8, 11, 14, 18, 21, 25, 30]
t = 18

first = 0 # индекс элемента с которого мы начинаем наш поиск
last = len(spisok) - 1 #индекс элемента на котором мы закончим наш поиск
index = -1 #Сюда запишем индекс, если найдем число
while (first <= last) and (index == -1):
    mid = (first + last) // 2 # Находим индекс элемента ровно посередине
    if spisok[mid] == t:
        index = mid # Если угадали, сохраняем индекс центрального элемента
    else:
        if t < spisok[mid]:
            last = mid - 1  # Если искомое меньше центра, отбрасываем правую половину
        else:
            first = mid + 1 # Если искомое больше центра, отбрасываем левую половину
if index != -1: # Если index изменился и больше не равен -1
    print("индекс элемента:", index)
else: # Если цикл закончился, а index так и остался равным -1
    print("элемент не найден в списке.")
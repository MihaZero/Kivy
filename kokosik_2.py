spisok =  [29, 10, 14, 37, 13]
for i in range(len(spisok)):# запускаем цикл,который по очереди перебирает все индексы списка от 0 до конца, чтобы заполнить их по возрастанию
    min = i# считаем i наименьшим элементом
    for j in range(i + 1, len(spisok)):# Этот цикл перебирает несортированные элементы
        if spisok[j] < spisok[min]:#если нашли элемент, который меньше нашего текущего минимума
            min= j #обновляем память компьютера,чтобы он считал наименьшим j
    spisok[i], spisok[min] = spisok[min], spisok[i]# Меняем местами два элемента.
    print(spisok)
print("исходный список:")
print(spisok)